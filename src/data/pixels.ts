/* The icon set, drawn pixel by pixel.

   Every icon is a 32 by 32 grid of characters, one row per string, the way
   ResEdit showed an icl8 resource. A character is a colour from the icon's
   palette; a dot is transparent. Icon.astro turns the grid into one SVG
   rect per run of colour with crisp edges, so the same drawing is sharp at
   32px, at 64px and on the phone, and there is no bitmap file anywhere.

   The palette is System 7's: black outlines, white, the four greys of the
   standard 34-colour icon palette, and a handful of the flat colours the
   Finder's own colour icons used. An icon may add a few of its own. */

/* What each one shows, and where a liberty was taken.

   hd         a wide drive case, darker top face, drive light bottom left
   folder     the manila folder, tab top left, darker back panel
   doc        blank page, folded top right corner, four lines of text
   textedit   the same page with a bold headline: a ReadMe
   pict       the same page with a framed landscape on it
   trash      ribbed can, lid with a handle
   trash-full the same can with crumpled paper pushing the lid up
   happy      the compact Mac that smiles at boot
   finder     the same Mac, face split light and dark
   mac        the same Mac, blank blue screen
   app        the generic application diamond, pen inside
   apple      the six colour Apple, sized for the menu bar
   caution    yellow triangle, exclamation mark
   stop       red octagon, white hand
   note       a face with a speech balloon
   balloon    balloon help: a speech balloon with a question mark
   volbase    white card, navy v
   rin        slate card, small cream face
   kyou       planner page, red header with a face, ruled lines
   market     a monitor with an orange line going up
   photos     a photo print: sky, hill, sun
   safari     a globe with meridians
   terminal   a monitor with a prompt and a cursor
   stickies   yellow note, corner turned up
   github     a folder with the alias arrow
   peter      head and shoulders, dithered shirt
   settings   a control panel with two sliders
   floppy     a 3.5 inch disk, shutter and label

   Liberties: the drawings follow System 7's rules (one pixel of black
   outline, flat fills, light from the top left, a black drop shadow under
   documents and folders) rather than copying any single Apple icon pixel
   for pixel. The four project icons and the six utility icons are new
   drawings in that idiom, because Apple never shipped an icon for them.
   `note` uses a face with a speech balloon rather than System 7's profile
   portrait, which does not survive being redrawn at this size. `github` is
   the folder with the alias arrow, the way an alias to a repository would
   actually have looked on that desktop. */

