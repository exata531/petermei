export const pixOf = (id: string): Pix => pix[id] ?? blank;

/* the grid as SVG rects: one per horizontal run of one colour */
export function pixSvg(id: string): string {
  const p = pixOf(id);
  const pal = { ...PAL, ...p.pal };
  const out: string[] = [];
  p.rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      let n = 1;
      while (x + n < row.length && row[x + n] === c) n++;
      if (c !== '.' && pal[c]) out.push(`<rect x="${x}" y="${y}" width="${n}" height="1" fill="${pal[c]}"/>`);
      x += n;
    }
  });
  return out.join('');
}
