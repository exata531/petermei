export const pixOf = (id: string, size: 16 | 32 = 32): Pix => (size === 16 ? pix16[id] : undefined) ?? pix[id] ?? blank;
/* the grid an icon will actually be drawn from at the size asked for, so the
   viewBox can match it */
export const pixSize = (id: string, size: 16 | 32 = 32): 16 | 32 => (size === 16 && pix16[id] ? 16 : 32);

/* the grid as SVG rects: one per horizontal run of one colour */
export function pixSvg(id: string, size: 16 | 32 = 32): string {
  const p = pixOf(id, size);
  const pal = { ...PAL, ...p.pal };
  const out: string[] = [];
  p.rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      let n = 1;
      while (x + n < row.length && row[x + n] === c) n++;
      if (c !== '.' && pal[c]) out.push(`<rect x="${x}" y="${y}" width="${n}" height="1" fill="${pal[c]}"/>`);
      x += n;
    }
  });
  return out.join('');
}
